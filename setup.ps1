<#
  setup.ps1 - first-time setup for a fresh machine (e.g. your friend's PC).

  Run ONCE after unzipping the project, with the exported transfer_data\
  folder sitting alongside it at .\transfer_data. It will:
    1. Load Docker images from transfer_data\docker_images.tar if present, so
       `docker compose up` doesn't need to pull anything from the internet.
    2. Start the containers (Postgres, Qdrant x8, pgAdmin, MLflow).
    3. Create the backend venv and install Python deps.
    4. Generate backend\.env with fresh secrets (if one doesn't exist yet).
    5. npm install the frontend.
    6. Restore the REAL data from transfer_data\ (Postgres + Qdrant + MLflow),
       falling back to the demo seed if that data isn't there or doesn't land.

  The fallback is checked, not assumed: after the dump is applied the users
  table is counted, and an empty one is treated as "the transfer didn't happen"
  and seeded instead - an empty users table means nobody can log in, which is
  the one outcome worse than demo data.

  The demo seed mirrors the real tenant list (same nine companies, same users,
  same budgets) - see backend\app\seed.py.

  After this runs once, use start.ps1 / run.bat for every day after.

  Usage:  .\setup.ps1
#>
$ErrorActionPreference = "Stop"
$root     = $PSScriptRoot
$backend  = Join-Path $root "backend"
$frontend = Join-Path $root "frontend"
$data     = Join-Path $root "transfer_data"

function Info($m) { Write-Host "[setup] $m" -ForegroundColor Cyan }
function Ok($m)   { Write-Host "[ ok  ] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "[warn ] $m" -ForegroundColor Yellow }

# --- 0) Docker images: load bundled ones instead of pulling -----------------
$imageTar = Join-Path $data "docker_images.tar"
if (Test-Path $imageTar) {
    Info "Loading Docker images from transfer_data (no internet pull needed)..."
    docker load -i $imageTar
} else {
    Info "No bundled images in transfer_data - 'docker compose up' will pull them."
}

# --- 1) Start containers -----------------------------------------------------
Info "Starting containers..."
Push-Location $root
docker compose up -d
Pop-Location

Info "Waiting for Postgres..."
$pgUp = $false
for ($i = 0; $i -lt 30; $i++) {
    docker exec orange-postgres pg_isready -U orange -d orange *> $null
    if ($LASTEXITCODE -eq 0) { $pgUp = $true; break }
    Start-Sleep -Seconds 2
}
if ($pgUp) { Ok "Postgres is ready." } else { Warn "Postgres never reported ready - check 'docker logs orange-postgres'." }

# --- 2) Backend venv + deps --------------------------------------------------
Info "Creating backend virtualenv and installing dependencies (a few minutes)..."
Push-Location $backend
python -m venv .venv
.\.venv\Scripts\pip.exe install -r requirements.txt --only-binary mmh3,fastembed
Pop-Location
Ok "Backend dependencies installed."

# --- 3) .env: generate fresh secrets if missing ------------------------------
$envFile = Join-Path $backend ".env"
if (-not (Test-Path $envFile)) {
    Info "Generating backend\.env with fresh secrets..."
    Copy-Item (Join-Path $backend ".env.example") $envFile
    $secretKey = & (Join-Path $backend ".venv\Scripts\python.exe") -c "import secrets; print(secrets.token_hex(32))"
    $jwtSecret = & (Join-Path $backend ".venv\Scripts\python.exe") -c "import secrets; print(secrets.token_hex(32))"
    $fernetKey = & (Join-Path $backend ".venv\Scripts\python.exe") -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"
    (Get-Content $envFile) `
        -replace 'SECRET_KEY=change-me', "SECRET_KEY=$secretKey" `
        -replace 'JWT_SECRET=change-me', "JWT_SECRET=$jwtSecret" `
        -replace '^FERNET_KEY=$', "FERNET_KEY=$fernetKey" |
        Set-Content $envFile
    Ok "backend\.env created. Add LLM API keys (GROQ_API_KEY etc.) to it if you want live providers."
} else {
    Ok "backend\.env already exists - leaving it alone."
}

# --- 4) Frontend deps ---------------------------------------------------------
Info "Installing frontend dependencies (npm install)..."
Push-Location $frontend
npm install
Pop-Location
Ok "Frontend dependencies installed."

# --- 5) Data: restore from transfer_data, else seed the demo ----------------
# Two ways to end up with a working database. The restore is preferred because
# it is the real thing; the seed exists so a machine with no transfer_data\ is
# still usable rather than a login screen no account can get past.
#
# The seed is NOT a lesser dataset: seed.py builds the same nine companies and
# the same users as the dump, on the same token budgets. What it cannot
# reproduce is history that was generated by real model calls - the seeders
# regenerate conversations and usage by actually querying the platform, so the
# numbers differ from the dump's even though the shape matches.

function Invoke-DemoSeed {
    Info "Seeding demo data (this asks real questions through the app - a few minutes)..."
    Push-Location $backend
    try {
        $py = ".\.venv\Scripts\python.exe"
        & $py -m app.seed
        & $py -m app.seed_docs
        & $py -m app.seed_providers
        & $py -m app.seed_pii_rules
        & $py -m app.seed_conversations
        & $py -m app.seed_usage_history
    } finally {
        Pop-Location
    }
    Ok "Demo data seeded. Log in as admin@orange.com / password123."
}

# Count the users table. Returns 0 if the table is missing or psql can't answer,
# which is exactly how a failed restore looks from the outside.
function Get-UserCount {
    $out = docker exec orange-postgres psql -U orange -d orange -tAc "select count(*) from users" 2>$null
    if ($LASTEXITCODE -ne 0) { return 0 }
    $n = 0
    if ([int]::TryParse(($out | Out-String).Trim(), [ref]$n)) { return $n }
    return 0
}

$pgDump   = Join-Path $data "postgres.sql"
$restored = $false

if (Test-Path $pgDump) {
    Info "Restoring REAL Postgres data from transfer_data\postgres.sql..."
    Get-Content $pgDump -Raw | docker exec -i orange-postgres psql -U orange -d orange

    # Verify rather than assume. psql exits 0 even when individual statements
    # failed, so "the command ran" says nothing about whether the rows landed.
    # An empty users table means nobody can log in - fall through to the seed.
    $users = Get-UserCount
    if ($users -lt 1) {
        Warn "The dump was applied but the users table is empty - the restore did not take."
        Warn "Scroll up for the psql errors. Falling back to demo data so the app is usable."
    } else {
        Ok "Postgres data restored ($users users)."
        $restored = $true
    }
} elseif (Test-Path $data) {
    Warn "transfer_data\ exists but postgres.sql isn't directly inside it (checked: $pgDump)."
    Warn "That is usually a nested-extraction issue - run 'Get-ChildItem -Recurse $data'"
    Warn "and move the files up so postgres.sql sits directly in transfer_data\."
    Warn "Continuing with demo data instead."
    Start-Sleep -Seconds 5
} else {
    Info "No transfer_data\ folder found - using demo data."
}

if ($restored) {
    Info "Restoring Qdrant volumes from transfer_data..."
    $qdrantContainers = @(
        "orange-qdrant",
        "orange-qdrant-ded-1", "orange-qdrant-ded-2", "orange-qdrant-ded-3",
        "orange-qdrant-ded-4", "orange-qdrant-ded-5", "orange-qdrant-ded-6", "orange-qdrant-ded-7"
    )
    foreach ($c in $qdrantContainers) {
        $tarFile = Join-Path $data "qdrant-$c.tar.gz"
        if (-not (Test-Path $tarFile)) { continue }
        $vol = docker inspect $c --format '{{ (index .Mounts 0).Name }}'
        docker stop $c | Out-Null
        docker run --rm -v "${vol}:/data" -v "${data}:/backup" busybox sh -c "rm -rf /data/* && tar xzf /backup/qdrant-$c.tar.gz -C /data"
        docker start $c | Out-Null
    }
    Ok "Qdrant data restored."

    $mlflowDataTar      = Join-Path $data "mlflow-data.tar.gz"
    $mlflowArtifactsTar = Join-Path $data "mlflow-artifacts.tar.gz"
    if ((Test-Path $mlflowDataTar) -or (Test-Path $mlflowArtifactsTar)) {
        Info "Restoring MLflow volumes from transfer_data..."
        docker stop orange-mlflow | Out-Null
        if (Test-Path $mlflowDataTar) {
            $vol = docker inspect orange-mlflow --format '{{ range .Mounts }}{{ if eq .Destination "/mlflow/data" }}{{ .Name }}{{ end }}{{ end }}'
            docker run --rm -v "${vol}:/data" -v "${data}:/backup" busybox sh -c "rm -rf /data/* && tar xzf /backup/mlflow-data.tar.gz -C /data"
        }
        if (Test-Path $mlflowArtifactsTar) {
            $vol = docker inspect orange-mlflow --format '{{ range .Mounts }}{{ if eq .Destination "/mlflow/artifacts" }}{{ .Name }}{{ end }}{{ end }}'
            docker run --rm -v "${vol}:/data" -v "${data}:/backup" busybox sh -c "rm -rf /data/* && tar xzf /backup/mlflow-artifacts.tar.gz -C /data"
        }
        docker start orange-mlflow | Out-Null
        Ok "MLflow data restored (runs, params, metrics, registry + artifacts)."
    }
} else {
    Invoke-DemoSeed
}

Write-Host ""
Ok "Setup complete."
Write-Host "Run .\start.ps1 (or double-click run.bat) from now on." -ForegroundColor DarkGray
